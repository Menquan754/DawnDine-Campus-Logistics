def build_system_prompt(now: datetime | None = None) -> str:
    """在系统提示词后补充当前日期，避免模型把“今天”理解错。"""

    moment = now or datetime.now()
    weekday = _WEEKDAY_NAMES[moment.weekday()]
    return (
        f"{SYSTEM_PROMPT}\n\n"
        f"【当前时间】今天是 {moment:%Y-%m-%d}（{weekday}），当前时间 {moment:%H:%M}。"
        "用户说“今天/明天/后天”时，按这个日期换算；不确定具体日期时先追问。"
    )
